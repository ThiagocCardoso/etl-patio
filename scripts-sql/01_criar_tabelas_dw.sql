DROP TABLE IF EXISTS fatoatendimento CASCADE;
DROP TABLE IF EXISTS dimtempo, dimhora, dimveiculo, dimservico, dimstatus, dimresponsavel CASCADE;
DROP TABLE IF EXISTS stg_atendimento, rej_atendimento, log_execucao CASCADE;

CREATE TABLE dimtempo (
  sk_tempo   INT PRIMARY KEY,
  data       DATE NOT NULL UNIQUE,
  dia        INT NOT NULL,
  dia_semana VARCHAR(15) NOT NULL,
  mes        INT NOT NULL,
  nome_mes   VARCHAR(15) NOT NULL,
  trimestre  INT NOT NULL,
  semestre   INT NOT NULL,
  ano        INT NOT NULL,
  dia_util   BOOLEAN NOT NULL
);

CREATE TABLE dimhora (
  sk_hora       INT PRIMARY KEY,
  faixa_periodo VARCHAR(10) NOT NULL
);

CREATE TABLE dimveiculo (
  sk_veiculo   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  placa        VARCHAR(8) NOT NULL UNIQUE,
  tipo_veiculo VARCHAR(50),
  marca        VARCHAR(50),
  modelo       VARCHAR(50)
);

CREATE TABLE dimservico (
  sk_servico        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_servico      VARCHAR(100) NOT NULL UNIQUE,
  categoria_servico VARCHAR(50)
);

CREATE TABLE dimstatus (
  sk_status    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome_status  VARCHAR(30) NOT NULL UNIQUE,
  ordem_status INT NOT NULL
);

CREATE TABLE dimresponsavel (
  sk_responsavel   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome_responsavel VARCHAR(100) NOT NULL UNIQUE,
  setor            VARCHAR(50)
);

CREATE TABLE fatoatendimento (
  id_atendimento                 INT PRIMARY KEY,
  sk_data_entrada                INT NOT NULL REFERENCES dimtempo(sk_tempo),
  sk_hora_entrada                INT NOT NULL REFERENCES dimhora(sk_hora),
  sk_data_conclusao              INT REFERENCES dimtempo(sk_tempo),
  sk_data_liberacao              INT REFERENCES dimtempo(sk_tempo),
  sk_veiculo                     INT NOT NULL REFERENCES dimveiculo(sk_veiculo),
  sk_servico                     INT NOT NULL REFERENCES dimservico(sk_servico),
  sk_status                      INT NOT NULL REFERENCES dimstatus(sk_status),
  sk_responsavel                 INT NOT NULL REFERENCES dimresponsavel(sk_responsavel),
  dt_hora_entrada                TIMESTAMP NOT NULL,
  dt_hora_inicio_manutencao      TIMESTAMP,
  dt_hora_conclusao              TIMESTAMP,
  dt_hora_liberacao              TIMESTAMP,
  km_entrada                     INT,
  tempo_permanencia_min          INT,
  tempo_ate_conclusao_min        INT,
  tempo_aguardando_liberacao_min INT,
  tempo_espera_min               INT,
  tempo_execucao_min             INT,
  qtd_atendimento                INT NOT NULL DEFAULT 1
);

CREATE INDEX idx_fato_veiculo  ON fatoatendimento (sk_veiculo);
CREATE INDEX idx_fato_servico  ON fatoatendimento (sk_servico);
CREATE INDEX idx_fato_data_ent ON fatoatendimento (sk_data_entrada);

CREATE TABLE stg_atendimento (
  id_registro                 VARCHAR(20),
  placa                       VARCHAR(30),
  data_hora_chegada           VARCHAR(30),
  quilometragem               VARCHAR(30),
  responsavel                 VARCHAR(100),
  servico                     VARCHAR(100),
  status                      VARCHAR(50),
  data_hora_inicio_manutencao VARCHAR(30),
  data_hora_termino           VARCHAR(30),
  data_hora_liberacao         VARCHAR(30),
  dt_carga                    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE rej_atendimento (
  id_rejeicao                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_registro                 VARCHAR(20),
  motivo                      VARCHAR(100) NOT NULL,
  placa                       VARCHAR(30),
  data_hora_chegada           VARCHAR(30),
  quilometragem               VARCHAR(30),
  responsavel                 VARCHAR(100),
  servico                     VARCHAR(100),
  status                      VARCHAR(50),
  data_hora_inicio_manutencao VARCHAR(30),
  data_hora_termino           VARCHAR(30),
  data_hora_liberacao         VARCHAR(30),
  dt_rejeicao                 TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE log_execucao (
  id_log             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job                VARCHAR(100) NOT NULL,
  inicio             TIMESTAMP,
  fim                TIMESTAMP,
  linhas_lidas       INT,
  linhas_carregadas  INT,
  linhas_rejeitadas  INT,
  linhas_descartadas INT,
  status             VARCHAR(20),
  mensagem           VARCHAR(500)
);
SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
ORDER BY table_name;
